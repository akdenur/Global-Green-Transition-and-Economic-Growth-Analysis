# Verileri temizlemek ve yılları satırlara indirmek (melt) için bir fonksiyon yazalım
def temizle_ve_erit(df, deger_ismi):
    # Dünya bankası verilerinde en sonda genelde içi boş 'Unnamed: 67' gibi bir sütun olur, onu temizleyelim
    df = df.loc[:, ~df.columns.str.contains('^Unnamed')]

    # Modele sokmayacağımız gereksiz etiket sütunlarını atalım
    silinecek_sutunlar = ['Country Code', 'Indicator Name', 'Indicator Code']
    df = df.drop(columns=silinecek_sutunlar, errors='ignore')

    # Melt işlemi: Yılları sütun olmaktan çıkarıp 'Year' adında tek bir sütuna topluyoruz
    df_melted = df.melt(id_vars=['Country Name'], var_name='Year', value_name=deger_ismi)

    # Yıl sütununu tam sayıya (integer) çevirelim (Örn: "2020" -> 2020)
    df_melted['Year'] = df_melted['Year'].astype(int)

    return df_melted

# 4 ana verimize de bu fonksiyonu uygulayalım
df_gdp_temiz = temizle_ve_erit(df_gdp, 'GDP_Per_Capita')
