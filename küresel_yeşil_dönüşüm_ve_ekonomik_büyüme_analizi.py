# 1. Prophet için veriyi hazırlama
# Prophet algoritması zaman sütununun adını 'ds', değerin adını 'y' olarak ister
df_prophet = df_gecmis[['Year', 'CO2_Emissions']].copy()

# Yılları Prophet'in anlayacağı tarih formatına (Örn: 2000 -> 2000-01-01) çeviriyoruz
df_prophet['ds'] = pd.to_datetime(df_prophet['Year'], format='%Y')
df_prophet['y'] = df_prophet['CO2_Emissions']

# 2. Modeli Kurma ve Eğitme
# Yıllık makroekonomik veri olduğu için günlük/haftalık mevsimselliği kapatıyoruz
model_prophet = Prophet(yearly_seasonality=False, weekly_seasonality=False, daily_seasonality=False)
model_prophet.fit(df_prophet)

# 3. Geleceği Simüle Etme (2023 - 2035 arası 13 yıl)
gelecek_adımlar = model_prophet.make_future_dataframe(periods=13, freq='YS') # YS = Yılın Başı
tahminler = model_prophet.predict(gelecek_adımlar)

# 4. Görselleştirme
plt.figure(figsize=(12, 6))

# Gerçek Veriler (Siyah Noktalar)
sns.scatterplot(x=df_prophet['ds'].dt.year, y=df_prophet['y'], color='black', s=60, label='Gerçekleşen Veri (2000-2022)')

# Prophet Tahmin Çizgisi (Mavi Çizgi)
sns.lineplot(x=tahminler['ds'].dt.year, y=tahminler['yhat'], color='tab:blue', linewidth=2.5, label='Prophet Tahmini (2035\'e kadar)')

