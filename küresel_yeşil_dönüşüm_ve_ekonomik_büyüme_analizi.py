from functools import reduce

# 1. Dört ana veriyi Country Name ve Year üzerinden yan yana birleştiriyoruz
tablolar = [df_gdp_temiz, df_co2_temiz, df_renew_temiz, df_rnd_temiz]
df_master = reduce(lambda sol, sag: pd.merge(sol, sag, on=['Country Name', 'Year'], how='outer'), tablolar)

# 2. Ülke metadata tablosundan sadece işimize yarayan kısımları alalım
# Dünya Bankası metadata dosyasında asıl ülke adları genelde 'TableName' sütununda yer alır
df_meta_temiz = df_meta[['TableName', 'Region', 'IncomeGroup']].rename(columns={'TableName': 'Country Name'})

# 3. Ana tablomuz ile ülke bilgilerini (kıta ve gelir durumu) eşleştiriyoruz
df_final = pd.merge(df_master, df_meta_temiz, on='Country Name', how='left')

# 4. Gerçek ülkeleri ayıklama operasyonu
# Region sütunu boş (NaN) olanlar ülke değil, bölgesel gruplardır (Dünya, Avrupa Birliği vs.). Onları siliyoruz.
df_final = df_final.dropna(subset=['Region'])

# Analizimiz için çok eski yıllarda veri kalitesi düşük olduğu için,
# milenyum sonrası döneme odaklanalım (2000 yılı ve sonrası)
df_final = df_final[df_final['Year'] >= 2000]

print("Birleştirme operasyonu başarılı! Tablonun boyutu (Satır, Sütun):", df_final.shape)
print("\nVerinin son hali:")
print(df_final.head())

# Üzerinde çalışacağımız sayısal sütunları seçiyoruz
sayisal_sutunlar = ['GDP_Per_Capita', 'CO2_Emissions', 'Renewable_Energy', 'RnD_Expenditure']

# 1. AŞAMA: Ülke içi doldurma (Enterpolasyon + İleri/Geri Doldurma)
# Her ülkeyi kendi içinde gruplayıp, boşlukları mantıklı bir çizgiyle (linear) dolduruyoruz
for sutun in sayisal_sutunlar:
    df_final[sutun] = df_final.groupby('Country Name')[sutun].transform(
        lambda x: x.interpolate(method='linear').bfill().ffill()
    )

# 2. AŞAMA: Kıta bazlı doldurma
# Eğer ülke tarihinde o veriyi hiç açıklamadıysa, o ülkenin eksiklerini bulunduğu kıtanın ortalaması ile dolduruyoruz
for sutun in sayisal_sutunlar:
    df_final[sutun] = df_final[sutun].fillna(df_final.groupby('Region')[sutun].transform('mean'))

# 3. Sonuç Kontrolü
